def save_analysis_to_db(scores: Dict[str, Any], parsed_resume: Optional[Dict] = None, filename: str = "uploaded_resume.pdf", job_title: Optional[str]=None):
    """Save scores and optional parsed resume data. Convert numpy types to native."""
    ensure_db()
    try:
        conn = sqlite3.connect(DB_PATH, check_same_thread=False)
        cursor = conn.cursor()
        # prepare fields
        ats_score = float(scores.get("final_score", 0) or 0)
        layout_score = float(scores.get("layout_score", 0) or 0)
        tfidf_score = float(scores.get("tfidf_score", 0) or 0)
        sbert_score = float(scores.get("sbert_score", 0) or 0)
        missing_skills = json_dumps_safe(scores.get("missing_skills", []))
        analysis_results = json_dumps_safe(scores)
        skills_json = None
        thumbnail = None
        latex = scores.get("latex") or None
        if parsed_resume:
            sk = parsed_resume.get("skills")
            if sk:
                skills_json = json_dumps_safe(sk)
            text = parsed_resume.get("text", "")
            # create thumbnail (cache)
            safe_name = filename.replace("/", "_").replace("\\", "_")
            thumb_path = os.path.join(THUMB_DIR, f"{safe_name}.jpg")
            if text and (not os.path.exists(thumb_path)):
                t = create_text_thumbnail(text, thumb_path)
                if t:
                    thumbnail = thumb_path
            elif os.path.exists(thumb_path):
                thumbnail = thumb_path

        cursor.execute('''
            INSERT INTO resume_analysis
            (filename, upload_date, ats_score, layout_score, tfidf_score, sbert_score, missing_skills, analysis_results, job_title, thumbnail_path, skills, latex)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        ''', (
            filename,
            datetime.now().isoformat(),
            ats_score,
            layout_score,
            tfidf_score,
            sbert_score,
            missing_skills,
            analysis_results,
            job_title,
            thumbnail,
            skills_json,
            latex
        ))
        conn.commit()
        conn.close()
    except Exception as e:
        st.error(f"Error saving analysis to DB: {e}")

