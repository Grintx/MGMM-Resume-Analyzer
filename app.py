def ensure_db():
    """Create DB and add optional columns if missing."""
    conn = sqlite3.connect(DB_PATH, check_same_thread=False)
    cursor = conn.cursor()
    cursor.execute('''
        CREATE TABLE IF NOT EXISTS resume_analysis (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            filename TEXT,
            upload_date TEXT,
            ats_score REAL,
            layout_score REAL,
            tfidf_score REAL,
            sbert_score REAL,
            missing_skills TEXT,
            extracted_entities TEXT,
            analysis_results TEXT
        )
    ''')
    conn.commit()
    # add optional columns: job_title, thumbnail_path, skills, latex (if not exists)
    existing_cols = [row[1] for row in cursor.execute("PRAGMA table_info(resume_analysis)").fetchall()]
    optional_additions = {
        "job_title": "ALTER TABLE resume_analysis ADD COLUMN job_title TEXT",
        "thumbnail_path": "ALTER TABLE resume_analysis ADD COLUMN thumbnail_path TEXT",
        "skills": "ALTER TABLE resume_analysis ADD COLUMN skills TEXT",
        "latex": "ALTER TABLE resume_analysis ADD COLUMN latex TEXT"
    }
    for col, query in optional_additions.items():
        if col not in existing_cols:
            try:
                cursor.execute(query)
                conn.commit()
            except Exception:
                pass
    conn.close()

def numpy_safe(obj):
    """Recursively convert numpy types to Python native so JSON serialization works."""
    if isinstance(obj, dict):
        return {k: numpy_safe(v) for k, v in obj.items()}
    if isinstance(obj, list):
        return [numpy_safe(v) for v in obj]
    if isinstance(obj, (np.floating, np.float32, np.float64)):
        return float(obj)
    if isinstance(obj, (np.integer,)):
        return int(obj)
    return obj

def json_dumps_safe(obj):
    """Serialize object to JSON safely (converting numpy types)."""
    try:
        return json.dumps(numpy_safe(obj), default=str)
    except Exception:
        return json.dumps(str(obj))

def create_download_link_bytes(bytes_data: bytes, filename: str, label: str = "Download"):
    b64 = base64.b64encode(bytes_data).decode()
    href = f'<a href="data:application/octet-stream;base64,{b64}" download="{filename}" style="padding:8px 12px;background:linear-gradient(90deg,#7b39ff,#9f6bff);color:white;border-radius:8px;text-decoration:none">{label}</a>'
    return href

def create_text_thumbnail(text: str, out_path: str, width=400, height=260):
    """Create a simple text-based thumbnail using Pillow fallback."""
    if Image is None:
        return None
    try:
        img = Image.new("RGB", (width, height), (19, 10, 30))
        draw = ImageDraw.Draw(img)
        try:
            font = ImageFont.truetype("arial.ttf", 13)
        except Exception:
            font = ImageFont.load_default()
        # Compose preview text: first 600 chars, wrapped
        txt = " ".join(text.strip().split())
        txt = txt[:800]
        words = txt.split(" ")
        lines = []
        line = ""
        for w in words:
            if len(line) + len(w) + 1 > 45:
                lines.append(line.strip())
                line = w
            else:
                line = (line + " " + w).strip()
        if line:
            lines.append(line.strip())
        y = 10
        color = (235, 226, 255)
        for ln in lines[:12]:
            draw.text((10, y), ln, font=font, fill=color)
            y += 18
        img.save(out_path, quality=75)
        return out_path
    except Exception:
        return None

