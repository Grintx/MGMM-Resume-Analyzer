def _save_text_file_and_get_path(text: str, out_name: str = "optimized_resume.txt") -> Optional[str]:
    """Create a UTF-8 text file and return its path."""
    try:
        out_path = out_name
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(text)
        return out_path
    except Exception:
        return None

